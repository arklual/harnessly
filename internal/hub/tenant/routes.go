package tenant

// Source is where a route takes its tenant from.
type Source string

const (
	// Space: a space id in the path.
	Space Source = "space"
	// Org: an organization id or slug in the path.
	Org Source = "org"
	// Machine: a machine id in the path; the machine's row names its space.
	Machine Source = "machine"
	// Doc: a document's slug in the path; the document's row names its space.
	Doc Source = "document"
	// Person: the signed-in person, whose own rows the route reads.
	Person Source = "person"
	// Token: a secret of the path or the request that names one thing: an invitation, a guest link, a site session.
	Token Source = "token"
	// Agent: the machine that calls, known by its key or its session.
	Agent Source = "agent"
	// Install: the installation as a whole; only its administrator or its own secret passes.
	Install Source = "installation"
	// None: the route touches no tenant's data.
	None Source = "none"
)

// Route is one registered route of the hub and what stands between it and a tenant's data.
type Route struct {
	// Pkg is the directory the route is registered in, from the root of the repository.
	Pkg string
	// Pattern is the route as it is registered; a part held in a variable or a constant is written <name>.
	Pattern string
	// Tenant is where the route takes its tenant from.
	Tenant Source
	// Check is what decides whether the caller may touch that tenant.
	Check string
	// Open says why the route checks nobody; set instead of Check.
	Open string
	// Later says why a route with a space id in its path still checks by hand rather than behind Guard.
	Later string
}

func guarded(pkg string, tenant Source, check string, patterns ...string) []Route {
	out := make([]Route, 0, len(patterns))
	for _, p := range patterns {
		out = append(out, Route{Pkg: pkg, Pattern: p, Tenant: tenant, Check: check})
	}
	return out
}

// manual is guarded for a route with a space id in its path that is not behind Guard yet, and why.
func manual(pkg string, tenant Source, check, later string, patterns ...string) []Route {
	out := guarded(pkg, tenant, check, patterns...)
	for i := range out {
		out[i].Later = later
	}
	return out
}

func open(pkg string, tenant Source, why string, patterns ...string) []Route {
	out := make([]Route, 0, len(patterns))
	for _, p := range patterns {
		out = append(out, Route{Pkg: pkg, Pattern: p, Tenant: tenant, Open: why})
	}
	return out
}

func all(groups ...[]Route) []Route {
	var out []Route
	for _, g := range groups {
		out = append(out, g...)
	}
	return out
}

