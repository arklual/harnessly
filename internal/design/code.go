package design

// A mockup into the product's code one to one: `harnessly design code <project> --to <folder>`.
//
// The folder is the application's repository; its profile, sinopia.export.json, says where things go and which router
// it uses. The export is rules over files, without a model: the same project, kit and profile give the same bytes.
//
//	<root>/pages/<name>.view.tsx        the page, as the view: kit imports from code, presets expanded, the library's
//	                                    variables, data from props                                    GENERATED
//	<root>/pages/<name>.fixtures.ts     the page's fixtures, as they are                               GENERATED
//	<root>/pages/<name>.stories.tsx     a story per page with the fixtures (profile "stories")         GENERATED
//	<root>/pages/<name>.view.test.tsx   the view renders its fixtures (profile "tests": "vitest")      GENERATED
//	<root>/<path of the file>           the local components and other files the pages import         GENERATED
//	<root>/pages/<name>.container.tsx   data, state and handlers: the developer's, written once        NEVER TOUCHED
//	routes                              by the profile's router: a route table or Next's app/ pages   GENERATED
//
// A generated file starts with a line that names its source and the hash of what was written. An export rewrites a
// generated file only when that hash still matches its content: a view edited by hand, or a file at a generated path
// that the export did not write, is a conflict, and an export with a conflict writes nothing.

import (
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"

	"github.com/ly-solutions/harnessly/internal/designkit"
)

// CodeProfileFile is the export profile in the application's repository.
const CodeProfileFile = "sinopia.export.json"

// CodeProfile is sinopia.export.json.
type CodeProfile struct {
	V int `json:"v"`
	// Root is the folder (relative to the repository) the views, fixtures and local components go to.
	Root string `json:"root"`
	// Router: "react-router" (a route table), "next-app" (app/<route>/page.tsx) or "none".
	Router string `json:"router"`
	// Routes: for react-router the route table's file (default <root>/routes.tsx); for next-app the app folder
	// (default app).
	Routes string `json:"routes,omitempty"`
	// Stories: write a Storybook story per page from its fixtures. Tests: "vitest" writes a test per view.
	Stories bool   `json:"stories,omitempty"`
	Tests   string `json:"tests,omitempty"`
}

// CodeFile is one file of an export and what happened to it: written, unchanged, created (a container), kept (a
// container that is there), conflict.
type CodeFile struct {
	Path    string `json:"path"`
	Status  string `json:"status"`
	Reason  string `json:"reason,omitempty"`
	Added   int    `json:"added,omitempty"`
	Removed int    `json:"removed,omitempty"`
}

// CodePage is a page of the export.
type CodePage struct {
	Name  string `json:"name"`
	ID    string `json:"id,omitempty"`
	Route string `json:"route,omitempty"`
	View  string `json:"view"`
}

// CodeSkip is a board that was not exported, and why.
type CodeSkip struct {
	File   string `json:"file"`
	Reason string `json:"reason"`
}

// CodeExport is the report of an export.
type CodeExport struct {
	Project     string                    `json:"project"`
	Kit         string                    `json:"kit"`
	Version     string                    `json:"version"`
	Target      string                    `json:"target"`
	DryRun      bool                      `json:"dryRun"`
	Strict      []designkit.StrictFinding `json:"strict,omitempty"`
	Pages       []CodePage                `json:"pages"`
	Files       []CodeFile                `json:"files"`
	NotExported []CodeSkip                `json:"notExported,omitempty"`
	Conflicts   int                       `json:"conflicts"`
	Changed     int                       `json:"changed"`
}

const codeMark = "// Generated by harnessly design code from "

var codeRevRe = regexp.MustCompile(`\brev:([0-9a-f]{16})\b`)

// ReadCodeProfile reads and checks a repository's export profile.
func ReadCodeProfile(target string) (CodeProfile, error) {
	var p CodeProfile
	raw, err := os.ReadFile(filepath.Join(target, CodeProfileFile))
	if err != nil {
		return p, fmt.Errorf("no %s in %s: write one, e.g. {\"v\": 1, \"root\": \"src/design\", \"router\": \"react-router\", \"stories\": false, \"tests\": \"vitest\"}", CodeProfileFile, target)
	}
	if err := json.Unmarshal(raw, &p); err != nil {
		return p, fmt.Errorf("%s: %v", CodeProfileFile, err)
	}
	if p.V != 1 {
		return p, fmt.Errorf("%s: v must be 1", CodeProfileFile)
	}
	if !safeRel(p.Root) {
		return p, fmt.Errorf("%s: root %q must be a folder inside the repository", CodeProfileFile, p.Root)
	}
	switch p.Router {
	case "react-router", "next-app", "none":
	case "":
		p.Router = "none"
	default:
		return p, fmt.Errorf("%s: router %q is not react-router, next-app or none", CodeProfileFile, p.Router)
	}
	if p.Routes == "" {
		switch p.Router {
		case "react-router":
			p.Routes = p.Root + "/routes.tsx"
		case "next-app":
			p.Routes = "app"
		}
	}
	if p.Routes != "" && !safeRel(p.Routes) {
		return p, fmt.Errorf("%s: routes %q must be inside the repository", CodeProfileFile, p.Routes)
	}
	if p.Tests != "" && p.Tests != "vitest" {
		return p, fmt.Errorf("%s: tests %q: only vitest is known", CodeProfileFile, p.Tests)
	}
	return p, nil
}

func safeRel(p string) bool {
	if p == "" || strings.HasPrefix(p, "/") || strings.Contains(p, "\\") {
		return false
	}
	c := filepath.ToSlash(filepath.Clean(p))
	return c != "." && c != ".." && !strings.HasPrefix(c, "../")
}

// codeName is a page's name as a component (events-list -> EventsList).
func codeName(name string) string {
	var b strings.Builder
	up := true
	for _, r := range name {
		switch {
		case r == '-' || r == '_':
			up = true
		case up:
			b.WriteString(strings.ToUpper(string(r)))
			up = false
		default:
			b.WriteRune(r)
		}
	}
	s := b.String()
	if s == "" || s[0] >= '0' && s[0] <= '9' {
		s = "Page" + s
	}
	return s
}

// relImport is the import specifier of file `to` from file `from` (both slash paths in the repository), without
// the extension.
func relImport(from, to string) string {
	rel, _ := filepath.Rel(filepath.Dir(from), to)
	rel = filepath.ToSlash(rel)
	rel = strings.TrimSuffix(rel, filepath.Ext(rel))
	if !strings.HasPrefix(rel, ".") {
		rel = "./" + rel
	}
	return rel
}

type plannedFile struct {
	path      string
	body      string
	source    string // what the mark names
	container bool
}

// ExportCode turns the project's page modules into the application's code under target. With dryRun nothing is
// written. A strict finding or a conflict stops it before anything is written.
func (l *Library) ExportCode(project, target string, dryRun bool) (*CodeExport, error) {
	target, err := filepath.Abs(target)
	if err != nil {
		return nil, err
	}
	prof, err := ReadCodeProfile(target)
	if err != nil {
		return nil, err
	}
	strict, err := l.CheckStrict(project, nil)
	if err != nil {
		return nil, err
	}
	rep := &CodeExport{Project: project, Kit: strict.Kit, Version: strict.Version, Target: target, DryRun: dryRun, Pages: []CodePage{}, Files: []CodeFile{}}
	if len(strict.Findings) > 0 {
		rep.Strict = strict.Findings
		return rep, errors.New("the mockup is not made of the kit only: fix the strict findings first (harnessly design check " + project + " --strict)")
	}
	c, err := l.strictCanvas(project)
	if err != nil {
		return nil, err
	}
	k := designkit.NewStrictKit(c)
	dir := l.ProjectDirOf(project)
	realDir, err := filepath.EvalSymlinks(dir)
	if err != nil {
		return nil, err
	}
	model := l.ReadModel(project)
	pageOf := map[string]Page{}
	if model != nil {
		for _, p := range model.Pages {
			pageOf[p.File] = p
		}
	}
	var planned []plannedFile
	copied := map[string]bool{}
	var queue []string // project-relative files the pages import, to copy
	var routes []CodePage
	for _, name := range l.PageSources(project) {
		srcRel := pagesDirname + "/" + name + pageSrcExt
		raw, ok := readProjectFile(realDir, srcRel)
		if !ok {
			continue
		}
		fixtures := "./" + name + pageFixtureEx
		mod, err := k.TransformModule(raw, fixtures)
		if err != nil {
			return nil, fmt.Errorf("%s: %v", srcRel, err)
		}
		comp := mod.Component
		if comp == "" {
			comp = codeName(name)
		}
		base := prof.Root + "/" + pagesDirname + "/" + name
		page := CodePage{Name: name, View: base + ".view.tsx"}
		if p, ok := pageOf[name+".dc.html"]; ok {
			page.ID = p.ID
			if p.Route != nil {
				page.Route = *p.Route
			}
		}
		from := project + " " + srcRel
		if page.ID != "" {
			from += " (page " + page.ID + ")"
		}
		planned = append(planned, plannedFile{path: page.View, body: mod.Source, source: from})
		queue = append(queue, localImports(realDir, srcRel, raw)...)
		hasFixtures := len(mod.Props) > 0
		fixturesRel := pagesDirname + "/" + name + pageFixtureEx + ".ts"
		if f := resolvePageFile(filepath.Join(realDir, pagesDirname, name+pageFixtureEx)); f != "" {
			rel, _ := filepath.Rel(realDir, f)
			fixturesRel = filepath.ToSlash(rel)
			hasFixtures = true
			queue = append(queue, fixturesRel)
		}
		props := func(prefix string) string {
			var parts []string
			for _, p := range mod.Props {
				parts = append(parts, p+"={"+prefix+p+"}")
			}
			if len(parts) == 0 {
				return ""
			}
			return " " + strings.Join(parts, " ")
		}
		fixturesImport := relImport(base+".container.tsx", prof.Root+"/"+fixturesRel)
		var cb strings.Builder
		fmt.Fprintf(&cb, "// The container of %s.view.tsx: the data, state and handlers of the page live here.\n", name)
		cb.WriteString("// harnessly design code wrote this file once and never changes it: replace the fixtures with the real data.\n")
		fmt.Fprintf(&cb, "import %s from \"./%s.view\";\n", comp, name)
		if len(mod.Props) > 0 {
			fmt.Fprintf(&cb, "import { %s } from %q;\n", strings.Join(mod.Props, ", "), fixturesImport)
		}
		fmt.Fprintf(&cb, "\nexport default function %sContainer() {\n  return <%s%s />;\n}\n", comp, comp, props(""))
		planned = append(planned, plannedFile{path: base + ".container.tsx", body: cb.String(), container: true})
		if prof.Stories {
			var sb strings.Builder
			sb.WriteString("import type { Meta, StoryObj } from \"@storybook/react\";\n")
			fmt.Fprintf(&sb, "import %s from \"./%s.view\";\n", comp, name)
			if hasFixtures && len(mod.Props) > 0 {
				fmt.Fprintf(&sb, "import * as fixtures from %q;\n", fixturesImport)
			}
			title := name
			if p, ok := pageOf[name+".dc.html"]; ok && p.Title != "" {
				title = p.Title
			}
			fmt.Fprintf(&sb, "\nconst meta: Meta<typeof %s> = { title: %q, component: %s };\nexport default meta;\n\n", comp, "Pages/"+title, comp)
			fmt.Fprintf(&sb, "export const Default: StoryObj<typeof %s> = {", comp)
			if len(mod.Props) > 0 {
				var args []string
				for _, p := range mod.Props {
					args = append(args, p+": fixtures."+p)
				}
				fmt.Fprintf(&sb, " args: { %s } ", strings.Join(args, ", "))
			}
			sb.WriteString("};\n")
			planned = append(planned, plannedFile{path: base + ".stories.tsx", body: sb.String(), source: from})
		}
		if prof.Tests == "vitest" {
			var tb strings.Builder
			tb.WriteString("import { expect, test } from \"vitest\";\nimport { renderToStaticMarkup } from \"react-dom/server\";\n")
			fmt.Fprintf(&tb, "import %s from \"./%s.view\";\n", comp, name)
			if len(mod.Props) > 0 {
				fmt.Fprintf(&tb, "import * as fixtures from %q;\n", fixturesImport)
			}
			fmt.Fprintf(&tb, "\ntest(%q, () => {\n  expect(renderToStaticMarkup(<%s%s />)).not.toBe(\"\");\n});\n", name+" renders its fixtures", comp, props("fixtures."))
			planned = append(planned, plannedFile{path: base + ".view.test.tsx", body: tb.String(), source: from})
		}
		rep.Pages = append(rep.Pages, page)
		if page.Route != "" {
			routes = append(routes, page)
		}
	}
	for len(queue) > 0 {
		rel := queue[0]
		queue = queue[1:]
		if copied[rel] {
			continue
		}
		copied[rel] = true
		raw, ok := readProjectFile(realDir, rel)
		if !ok {
			continue
		}
		body := raw
		if ext := filepath.Ext(rel); ext == ".tsx" || ext == ".jsx" || ext == ".ts" || ext == ".js" {
			if !strings.Contains(filepath.Base(rel), pageFixtureEx+".") {
				mod, err := k.TransformModule(raw, "")
				if err != nil {
					return nil, fmt.Errorf("%s: %v", rel, err)
				}
				body = mod.Source
			}
			queue = append(queue, localImports(realDir, rel, raw)...)
		}
		planned = append(planned, plannedFile{path: prof.Root + "/" + rel, body: body, source: project + " " + rel})
	}
	sort.Slice(routes, func(i, j int) bool { return routes[i].Route < routes[j].Route })
	switch prof.Router {
	case "react-router":
		var rb strings.Builder
		for _, p := range routes {
			fmt.Fprintf(&rb, "import %sContainer from %q;\n", codeName(p.Name), relImport(prof.Routes, prof.Root+"/"+pagesDirname+"/"+p.Name+".container.tsx"))
		}
		rb.WriteString("\n// The pages of the mockup by their routes (React Router's route objects).\nexport const routes = [\n")
		for _, p := range routes {
			fmt.Fprintf(&rb, "  { path: %q, Component: %sContainer },\n", p.Route, codeName(p.Name))
		}
		rb.WriteString("];\n")
		planned = append(planned, plannedFile{path: prof.Routes, body: rb.String(), source: project + " routes"})
	case "next-app":
		for _, p := range routes {
			seg := strings.Trim(p.Route, "/")
			file := prof.Routes + "/page.tsx"
			if seg != "" {
				file = prof.Routes + "/" + seg + "/page.tsx"
			}
			body := fmt.Sprintf("export { default } from %q;\n", relImport(file, prof.Root+"/"+pagesDirname+"/"+p.Name+".container.tsx"))
			planned = append(planned, plannedFile{path: file, body: body, source: project + " route " + p.Route})
		}
	}
	for _, b := range l.boardFiles(project) {
		if _, built := l.BoardIsBuilt(project, b); built {
			continue
		}
		rep.NotExported = append(rep.NotExported, CodeSkip{File: b, Reason: "a board in the old format: harnessly design migrate --to tsx " + project + " turns it into a page module first"})
	}
	// Plan every file, then write only when nothing conflicts.
	realTarget, err := filepath.EvalSymlinks(target)
	if err != nil {
		return nil, err
	}
	var writes []plannedFile
	seen := map[string]bool{}
	for _, f := range planned {
		if seen[f.path] {
			continue
		}
		seen[f.path] = true
		abs, err := codeDest(realTarget, f.path)
		if err != nil {
			return rep, err
		}
		content := f.body
		if !f.container {
			content = stampCode(f.path, f.source, f.body)
		}
		cf := CodeFile{Path: f.path}
		old, err := os.ReadFile(abs)
		switch {
		case err != nil && f.container:
			cf.Status = "created"
			writes = append(writes, plannedFile{path: abs, body: content})
		case err != nil:
			cf.Status = "written"
			cf.Added = strings.Count(content, "\n")
			writes = append(writes, plannedFile{path: abs, body: content})
		case f.container:
			cf.Status = "kept"
		case string(old) == content:
			cf.Status = "unchanged"
		default:
			if why := codeConflict(string(old)); why != "" {
				cf.Status, cf.Reason = "conflict", why
				rep.Conflicts++
				break
			}
			cf.Status = "written"
			cf.Added, cf.Removed = lineDiff(string(old), content)
			writes = append(writes, plannedFile{path: abs, body: content})
		}
		if cf.Status == "written" || cf.Status == "created" {
			rep.Changed++
		}
		rep.Files = append(rep.Files, cf)
	}
	if rep.Conflicts > 0 {
		return rep, fmt.Errorf("%d file(s) changed by hand since the last export: nothing was written. Carry the change into the mockup or the container, then delete or restore the file", rep.Conflicts)
	}
	if dryRun {
		return rep, nil
	}
	for _, w := range writes {
		if err := os.MkdirAll(filepath.Dir(w.path), 0o755); err != nil {
			return rep, err
		}
		if err := writeReplacing(w.path, w.body); err != nil {
			return rep, err
		}
	}
	return rep, nil
}

// readProjectFile reads a file of the project by its project-relative path, only when it really lies inside the
// project: a symbolic link that leads out of it is not read.
func readProjectFile(realDir, rel string) (string, bool) {
	if !safeRel(rel) {
		return "", false
	}
	real, err := filepath.EvalSymlinks(filepath.Join(realDir, filepath.FromSlash(rel)))
	if err != nil || !insideProject(realDir, real) {
		return "", false
	}
	return readStrictFile(real)
}

// codeDest is where a planned file of the export goes in the target repository: its path must stay inside the
// repository, with no "." or ".." segment, and no folder or file on the way may be a symbolic link.
func codeDest(realTarget, rel string) (string, error) {
	if !safeRel(rel) {
		return "", fmt.Errorf("%s: the path leaves the repository", rel)
	}
	for _, seg := range strings.Split(rel, "/") {
		if seg == "" || seg == "." || seg == ".." {
			return "", fmt.Errorf("%s: the path has an empty, \".\" or \"..\" part", rel)
		}
	}
	at := realTarget
	for _, seg := range strings.Split(rel, "/") {
		at = filepath.Join(at, seg)
		st, err := os.Lstat(at)
		if os.IsNotExist(err) {
			break
		}
		if err != nil {
			return "", err
		}
		if st.Mode()&os.ModeSymlink != 0 {
			return "", fmt.Errorf("%s: a symbolic link on the way, the export does not write through it", rel)
		}
	}
	return filepath.Join(realTarget, filepath.FromSlash(rel)), nil
}

// writeReplacing writes a file through a temporary one renamed into place, so an existing file is replaced, never
// followed.
func writeReplacing(path, body string) error {
	tmp, err := os.CreateTemp(filepath.Dir(path), ".export-*")
	if err != nil {
		return err
	}
	if _, err := tmp.WriteString(body); err != nil {
		tmp.Close()
		os.Remove(tmp.Name())
		return err
	}
	if err := tmp.Close(); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	if err := os.Rename(tmp.Name(), path); err != nil {
		os.Remove(tmp.Name())
		return err
	}
	return nil
}

// stampCode is a generated file: the mark naming its source and the hash of the body, then the body.
func stampCode(path, source, body string) string {
	sum := sha256.Sum256([]byte(body))
	ext := filepath.Ext(path)
	if ext != ".ts" && ext != ".tsx" && ext != ".js" && ext != ".jsx" {
		return body
	}
	return codeMark + source + " rev:" + hex.EncodeToString(sum[:8]) + ". Do not edit: change the mockup, or the container next to it.\n" + body
}

// codeConflict says why an existing file must not be overwritten, "" when it is an untouched generated file.
func codeConflict(old string) string {
	head, body, _ := strings.Cut(old, "\n")
	if !strings.HasPrefix(head, codeMark) {
		return "the file is not one the export wrote"
	}
	m := codeRevRe.FindStringSubmatch(head)
	sum := sha256.Sum256([]byte(body))
	if m == nil || m[1] != hex.EncodeToString(sum[:8]) {
		return "edited by hand since the export wrote it"
	}
	return ""
}

// lineDiff counts the lines added and removed between two texts (by their longest common subsequence).
func lineDiff(a, b string) (added, removed int) {
	x, y := strings.Split(a, "\n"), strings.Split(b, "\n")
	if len(x)*len(y) > 4_000_000 {
		return len(y), len(x)
	}
	prev := make([]int, len(y)+1)
	for i := 1; i <= len(x); i++ {
		cur := make([]int, len(y)+1)
		for j := 1; j <= len(y); j++ {
			if x[i-1] == y[j-1] {
				cur[j] = prev[j-1] + 1
			} else {
				cur[j] = max(prev[j], cur[j-1])
			}
		}
		prev = cur
	}
	common := prev[len(y)]
	return len(y) - common, len(x) - common
}

// localImports are the project files a module imports by relative paths (project-relative slash paths).
func localImports(realDir, rel, src string) []string {
	var out []string
	for _, imp := range designkit.ScanImports(src) {
		if !strings.HasPrefix(imp.From, "./") && !strings.HasPrefix(imp.From, "../") {
			continue
		}
		f := resolvePageFile(filepath.Join(realDir, filepath.FromSlash(filepath.Dir(rel)), filepath.FromSlash(imp.From)))
		if f == "" {
			continue
		}
		real, err := filepath.EvalSymlinks(f)
		if err != nil || !insideProject(realDir, real) {
			continue
		}
		r, _ := filepath.Rel(realDir, real)
		r = filepath.ToSlash(r)
		if strings.HasPrefix(r, pagesDirname+"/") && strings.HasSuffix(r, pageSrcExt) && !strings.Contains(r, pageFixtureEx) {
			continue // another page: it is exported as a page
		}
		out = append(out, r)
	}
	return out
}

// boardFiles are the project's board files (*.dc.html at the top of project/).
func (l *Library) boardFiles(project string) []string {
	entries, err := os.ReadDir(l.ProjectDirOf(project))
	if err != nil {
		return nil
	}
	var out []string
	for _, e := range entries {
		if !e.IsDir() && strings.HasSuffix(e.Name(), ".dc.html") {
			out = append(out, e.Name())
		}
	}
	sort.Strings(out)
	return out
}
