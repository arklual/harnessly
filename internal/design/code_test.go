const codeTestdata = "testdata/code"

// copyTree copies a folder of the test data.
func copyTestTree(t *testing.T, from, to string) {
	t.Helper()
	err := filepath.WalkDir(from, func(p string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		rel, _ := filepath.Rel(from, p)
		dst := filepath.Join(to, rel)
		if d.IsDir() {
			return os.MkdirAll(dst, 0o755)
		}
		raw, err := os.ReadFile(p)
		if err != nil {
			return err
		}
		return os.WriteFile(dst, raw, 0o644)
	})
	if err != nil {
		t.Fatal(err)
	}
}

// kitBundle is the package's components.js as the kit's classic browser script, with the preset the kit declares.
func kitBundle(t *testing.T) string {
	raw := readFileT(t, filepath.Join(codeTestdata, "package", "acme-ui", "components.js"))
	return "(function () {\n" + strings.Replace(raw, "export function make", "function make", 1) + `
  var c = make(window.React);
  c.PrimaryButton = function (props) { return window.React.createElement(c.Button, Object.assign({ variant: "primary" }, props)); };
  window.Acme = c;
})();
`
}

// codeRig is the sample: the kit installed, the project "events" in a library, the application in app/.
func codeRig(t *testing.T, root string) (l *Library, project, app string) {
	t.Helper()
	t.Setenv("RUNTIME_LOCALE", "")
	lib, kits := filepath.Join(root, "lib"), filepath.Join(root, "kits")
	kit := filepath.Join(kits, "acme-ui", "1.0.0")
	copyTestTree(t, filepath.Join(codeTestdata, "kit"), kit)
	writeFile(t, filepath.Join(kit, "components", "bundle.js"), kitBundle(t))
	copyTestTree(t, filepath.Join(codeTestdata, "project"), filepath.Join(lib, "events"))
	app = filepath.Join(root, "app")
	copyTestTree(t, filepath.Join(codeTestdata, "app"), app)
	copyTestTree(t, filepath.Join(codeTestdata, "package"), filepath.Join(root, "package"))
	l = New(Config{LibraryDir: lib, KitsDir: kits, Texts: Texts{Tag: "test-design", CLI: "acme"}})
	t.Cleanup(func() { l.StopWatching(); l.StopPages() })
	return l, filepath.Join(lib, "events", "project"), app
}

func TestDesignCodeExportsTheViews(t *testing.T) {
	root, _ := filepath.EvalSymlinks(t.TempDir())
	l, _, app := codeRig(t, root)

	rep, err := l.ExportCode("events", app, true)
	if err != nil {
		t.Fatalf("dry run: %v %+v", err, rep)
	}
	if _, err := os.Stat(filepath.Join(app, "src", "design")); err == nil {
		t.Fatal("a dry run wrote files")
	}
	rep, err = l.ExportCode("events", app, false)
	if err != nil {
		t.Fatalf("export: %v %+v", err, rep)
	}
	if len(rep.Pages) != 1 || rep.Pages[0].Route != "/events" || rep.Pages[0].ID != "01JC0000000000000000000001" {
		t.Fatalf("pages: %+v", rep.Pages)
	}
	read := func(rel string) string { return readFileT(t, filepath.Join(app, filepath.FromSlash(rel))) }
	view := read("src/design/pages/events.view.tsx")
	for _, want := range []string{
		"// Generated by harnessly design code from events pages/events.tsx (page 01JC0000000000000000000001) rev:",
		`import { Button, Card, Root, Stack, Text } from "@acme/ui";`, // presets expanded, one import per module
		`import type * as fixtureData from "./events.fixtures";`,
		"export type EventsData = {\n  summary: typeof fixtureData.summary;\n  events: typeof fixtureData.events;\n};",
		"export default function Events({ summary, events }: EventsData) {",
		`<Button variant="primary">Create event</Button>`,
		`import { Stat } from "../components/stat";`,
	} {
		if !strings.Contains(view, want) {
			t.Errorf("the view lacks %q:\n%s", want, view)
		}
	}
	if strings.Contains(view, "PrimaryButton") {
		t.Errorf("the preset is left in the view:\n%s", view)
	}
	stat := read("src/design/components/stat.tsx")
	if !strings.Contains(stat, `color: "var(--acme-color-accent)"`) || !strings.Contains(stat, `gap: "var(--acme-space-2)"`) {
		t.Errorf("the token variables are not the library's:\n%s", stat)
	}
	if fx := read("src/design/pages/events.fixtures.ts"); !strings.Contains(fx, `name: "Spring concert"`) {
		t.Errorf("fixtures: %s", fx)
	}
	container := read("src/design/pages/events.container.tsx")
	if strings.HasPrefix(container, "// Generated") || !strings.Contains(container, "return <Events summary={summary} events={events} />;") ||
		!strings.Contains(container, `import { summary, events } from "./events.fixtures";`) {
		t.Errorf("container:\n%s", container)
	}
	routes := read("src/design/routes.tsx")
	if !strings.Contains(routes, `import EventsContainer from "./pages/events.container";`) || !strings.Contains(routes, `{ path: "/events", Component: EventsContainer },`) {
		t.Errorf("routes:\n%s", routes)
	}
	if s := read("src/design/pages/events.stories.tsx"); !strings.Contains(s, "args: { summary: fixtures.summary, events: fixtures.events }") {
		t.Errorf("story:\n%s", s)
	}
	if s := read("src/design/pages/events.view.test.tsx"); !strings.Contains(s, "renderToStaticMarkup(<Events summary={fixtures.summary} events={fixtures.events} />)") {
		t.Errorf("test:\n%s", s)
	}

	// The same mockup again: nothing changes.
	rep, err = l.ExportCode("events", app, false)
	if err != nil || rep.Changed != 0 {
		t.Fatalf("second export: %v %+v", err, rep.Files)
	}

	// The developer's container is never touched; a change of the mockup reaches the view.
	writeFile(t, filepath.Join(app, "src", "design", "pages", "events.container.tsx"), "export default function EventsContainer() { return null; }\n")
	page := filepath.Join(root, "lib", "events", "project", "pages", "events.tsx")
	writeFile(t, page, strings.Replace(readFileT(t, page), "Create event", "New event", 1))
	rep, err = l.ExportCode("events", app, false)
	if err != nil || rep.Changed != 1 {
		t.Fatalf("export after a change: %v %+v", err, rep.Files)
	}
	if !strings.Contains(read("src/design/pages/events.view.tsx"), "New event") || read("src/design/pages/events.container.tsx") != "export default function EventsContainer() { return null; }\n" {
		t.Fatal("the view did not follow, or the container was touched")
	}

	// A view edited by hand is a conflict: nothing is written.
	viewFile := filepath.Join(app, "src", "design", "pages", "events.view.tsx")
	writeFile(t, viewFile, readFileT(t, viewFile)+"// mine\n")
	writeFile(t, page, strings.Replace(readFileT(t, page), "New event", "Add event", 1))
	rep, err = l.ExportCode("events", app, false)
	if err == nil || rep.Conflicts != 1 || strings.Contains(read("src/design/pages/events.view.tsx"), "Add event") {
		t.Fatalf("conflict: %v %+v", err, rep)
	}
}

