// TestDesignCodeProof leaves the sample for web/scripts/design-code-proof.mjs: the mockup's board built with the
// built-in engine and the kit's files next to it (mockup/), the exported application (app/), built (app/dist/), with
// its node_modules linked to the package and to React. Run with DESIGN_CODE_PROOF=<empty dir> and
// DESIGN_CODE_NODE_MODULES=<a node_modules with react, react-dom and their types> (web/node_modules).
func TestDesignCodeProof(t *testing.T) {
	out, modules := os.Getenv("DESIGN_CODE_PROOF"), os.Getenv("DESIGN_CODE_NODE_MODULES")
	if out == "" || modules == "" {
		t.Skip("DESIGN_CODE_PROOF names the folder to leave the proof in, DESIGN_CODE_NODE_MODULES the node_modules with React")
	}
	l, project, app := codeRig(t, out)
	if b := l.BuildPage("events", "events"); b.Status != "built" {
		t.Fatalf("build: %+v", b)
	}
	if _, err := l.ExportCode("events", app, false); err != nil {
		t.Fatal(err)
	}
	mock := filepath.Join(out, "mockup")
	writeFile(t, filepath.Join(mock, "index.html"), readFileT(t, filepath.Join(project, "events.dc.html")))
	writeFile(t, filepath.Join(mock, "support.js"), readFileT(t, "ownengine/support.js"))
	copyTestTree(t, filepath.Join(out, "kits", "acme-ui", "1.0.0"), filepath.Join(mock, "ds", "acme-ui"))

	// The application's node_modules: the package itself, React from the given folder.
	nm := filepath.Join(app, "node_modules")
	link := func(name, to string) {
		dst := filepath.Join(nm, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(dst), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.Symlink(to, dst); err != nil {
			t.Fatal(err)
		}
	}
	link("@acme/ui", filepath.Join(out, "package", "acme-ui"))
	for _, m := range []string{"react", "react-dom", "@types/react", "@types/react-dom"} {
		link(m, filepath.Join(modules, filepath.FromSlash(m)))
	}
	// The build of the target: the bundler resolves every import of the exported code, the package's included.
	res := api.Build(api.BuildOptions{
		EntryPoints: []string{filepath.Join(app, "src", "main.tsx")}, AbsWorkingDir: app, Bundle: true, Write: true,
		Outdir: filepath.Join(app, "dist"), Format: api.FormatESModule, Platform: api.PlatformBrowser, JSX: api.JSXAutomatic,
		Define: map[string]string{"process.env.NODE_ENV": `"production"`}, LogLevel: api.LogLevelSilent, NodePaths: []string{nm},
		Loader: map[string]api.Loader{".css": api.LoaderCSS},
	})
	for _, e := range res.Errors {
		loc := ""
		if e.Location != nil {
			loc = fmt.Sprintf("%s:%d: ", e.Location.File, e.Location.Line)
		}
		t.Errorf("build: %s%s", loc, e.Text)
	}
}

func TestDesignCodeStaysInsideTheProjectAndTheRepository(t *testing.T) {
	root, _ := filepath.EvalSymlinks(t.TempDir())
	l, project, app := codeRig(t, root)
	// A symbolic link in the target on the way to a view: nothing is written through it.
	outside := filepath.Join(root, "outside")
	if err := os.MkdirAll(outside, 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.Symlink(outside, filepath.Join(app, "src", "design")); err != nil {
		t.Fatal(err)
	}
	if _, err := l.ExportCode("events", app, false); err == nil || !strings.Contains(err.Error(), "symbolic link") {
		t.Fatalf("a link in the target: %v", err)
	}
	if entries, _ := os.ReadDir(outside); len(entries) != 0 {
		t.Fatalf("written through the link: %v", entries)
	}
	if err := os.Remove(filepath.Join(app, "src", "design")); err != nil {
		t.Fatal(err)
	}
	// A component the page imports that is a link out of the project is not copied.
	secret := filepath.Join(root, "secret.tsx")
	writeFile(t, secret, "export const Secret = 1;\n")
	if _, ok := readProjectFile(project, "components/x.tsx"); ok {
		t.Fatal("a missing file was read")
	}
	if err := os.Symlink(secret, filepath.Join(project, "components", "x.tsx")); err != nil {
		t.Fatal(err)
	}
	if _, ok := readProjectFile(project, "components/x.tsx"); ok {
		t.Fatal("a link out of the project was read")
	}
	for _, bad := range []string{"../x/page.tsx", "app/../../x.tsx", "app/./x.tsx", "/abs.tsx"} {
		if _, err := codeDest(app, bad); err == nil {
			t.Errorf("%s: accepted", bad)
		}
	}
}
