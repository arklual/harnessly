#!/usr/bin/env python3
"""Builds the voice agent's head (web/app/next/features/voice-live/voice-head-svg.tsx and styles/voice-head.css) from
the designer's mascot: harnessly-mascot.svg (markup) and mascot.css (styles). Classes get the hx-head prefix, keyframes
too; the storyboard's frames (data-f) are left out. Run: tools/voice-head/gen.py <mascot dir> <web/app/next>."""
import re, sys, pathlib

src, out = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2])
svg = (src / 'harnessly-mascot.svg').read_text()
css = (src / 'mascot.css').read_text()

body = svg[svg.index('</style>') + 8 if '</style>' in svg else svg.index('>') + 1 : svg.rindex('</svg>')].strip()
body = re.sub(r'<!--.*?-->', '', body, flags=re.S)
classes = set()
for m in re.finditer(r'class="([^"]+)"', body):
    classes.update(m.group(1).split())
for m in re.finditer(r'\.([a-z][a-z0-9-]*)', css):
    if m.group(1) != 'm':
        classes.add(m.group(1))
classes.discard('m')

def cls(m):
    return 'className="' + ' '.join('hx-head__' + c for c in m.group(1).split()) + '"'
jsx = re.sub(r'class="([^"]+)"', cls, body)
jsx = re.sub(r'\s(stop-color|stop-opacity|stroke-width|stroke-linecap|stroke-linejoin)=',
             lambda m: ' ' + re.sub(r'-(\w)', lambda x: x.group(1).upper(), m.group(1)) + '=', jsx)
jsx = jsx.replace('id="mg-soft"', 'id="hx-head-soft"')
jsx = re.sub(r'/>', ' />', jsx)
jsx = re.sub(r'><', '>\n<', jsx)

css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
css = '\n'.join(l for l in css.split('\n') if 'data-f' not in l and l.strip())
css = re.sub(r'(?<![\w-])\.m(?![\w-])', '.hx-head', css)
css = re.sub(r'(?<![\d-])\.([a-z][a-z0-9-]*)', lambda m: '.hx-head__' + m.group(1) if m.group(1) in classes else m.group(0), css)
css = re.sub(r'(?<![\w-])m-(lx|tv|hue-s|hue|breathe|blink|ring|spin)\b', r'hx-head-\1', css)
css = css.replace('url(#mg-soft)', 'url(#hx-head-soft)').replace('var(--ms,96px)', 'var(--hx-head-size,26px)')
css += '\n/* The page leads the mouth by the voice\'s loudness (VoiceHead writes --m-tv each frame): no talking loop then. */\n'
css += '.hx-head[data-vol]{animation:hx-head-lx 2.6s ease-in-out infinite}\n'
css += '/* Typed words take the line: the head steps aside. */\n.hx-composer__voice[data-typed] .hx-head{display:none}\n'
head = ("/* The voice agent's head, generated by tools/voice-head/gen.py from the designer's mascot (harnessly design project,\n"
        " * mascot/): do not edit by hand, run the script. @property must stay global (it does not work in a shadow root). */\n")
(out / 'styles' / 'voice-head.css').write_text(head + css + '\n')

ind = '\n'.join('    ' + l for l in jsx.split('\n'))
(out / 'features' / 'voice-live' / 'voice-head-svg.tsx').write_text(
    "// Generated by tools/voice-head/gen.py from the designer's mascot (harnessly design project, mascot/). Do not edit.\n"
    "const VoiceHeadParts = () => (\n  <>\n" + ind + "\n  </>\n);\n\nexport default VoiceHeadParts;\n")
